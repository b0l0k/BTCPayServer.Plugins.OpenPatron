    // ── JSON round-trip tests ──

    [Fact]
    public void BlockDefinitionJsonRoundTrip()
    {
        var block = new BlockDefinition
        {
            Id = "test123",
            Type = "profile-hero",
            Settings = JObject.FromObject(new { showAvatar = true, showBio = false })
        };

        var json = JsonConvert.SerializeObject(block);
        var deserialized = JsonConvert.DeserializeObject<BlockDefinition>(json);

        Assert.NotNull(deserialized);
        Assert.Equal("test123", deserialized!.Id);
        Assert.Equal("profile-hero", deserialized.Type);
        Assert.NotNull(deserialized.Settings);
        Assert.True(deserialized.Settings!["showAvatar"]!.Value<bool>());
        Assert.False(deserialized.Settings["showBio"]!.Value<bool>());
    }

    [Fact]
    public void BlockDefinitionWithNullSettingsSerializes()
    {
        var block = new BlockDefinition { Id = "abc", Type = "description", Settings = null };
        var json = JsonConvert.SerializeObject(block);
        var deserialized = JsonConvert.DeserializeObject<BlockDefinition>(json);

        Assert.NotNull(deserialized);
        Assert.Equal("description", deserialized!.Type);
        Assert.Null(deserialized.Settings);
    }

    [Fact]
    public void FullSettingsJsonRoundTrip()
    {
        var settings = new OpenPatronAppSettings
        {
            PageType = OpenPatronPageType.Personal,
            PageTypeConfirmed = true,
            PageLayout =
            [
                new() { Id = "b1", Type = "profile-hero" },
                new() { Id = "b2", Type = "description", Settings = JObject.FromObject(new { title = "About me" }) }
            ],
            Theme = new PageTheme { AccentColor = "#00ff00", BorderRadius = "2rem", BlockSpacing = "0.5rem" },
            DisplayName = "Jane",
            AccentColor = "#00ff00"
        };

        var json = JsonConvert.SerializeObject(settings);
        var deserialized = JsonConvert.DeserializeObject<OpenPatronAppSettings>(json);

        Assert.NotNull(deserialized);
        Assert.Equal(2, deserialized!.PageLayout!.Count);
        Assert.Equal("profile-hero", deserialized.PageLayout[0].Type);
        Assert.Equal("About me", deserialized.PageLayout[1].Settings!["title"]!.Value<string>());
        Assert.Equal("#00ff00", deserialized.Theme!.AccentColor);
        Assert.Equal("2rem", deserialized.Theme.BorderRadius);
        Assert.Equal("Jane", deserialized.DisplayName);
    }

