    [Fact]
    public void BlockListOrderPreservedThroughSerialization()
    {
        var blocks = new List<BlockDefinition>
        {
            new() { Id = "1", Type = "sponsor-wall" },
            new() { Id = "2", Type = "profile-hero" },
            new() { Id = "3", Type = "description" },
        };

        var json = JsonConvert.SerializeObject(blocks);
        var deserialized = JsonConvert.DeserializeObject<List<BlockDefinition>>(json);

        Assert.Equal(3, deserialized!.Count);
        Assert.Equal("sponsor-wall", deserialized[0].Type);
        Assert.Equal("profile-hero", deserialized[1].Type);
        Assert.Equal("description", deserialized[2].Type);
    }
